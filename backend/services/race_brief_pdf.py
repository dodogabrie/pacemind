"""Render a race-brief dict to a single-page PDF artifact.

Uses fpdf2 (pure-Python, no system deps) so we can ship without rebuilding
the container with cairo/pango. Layout is intentionally simple — runners
read this on their phone or print it once before the start line.
"""

from __future__ import annotations

from typing import Dict, Optional

from fpdf import FPDF

# Brand-ish slate/emerald palette matching the frontend.
INK = (15, 23, 42)
MUTED = (100, 116, 139)
ACCENT = (4, 120, 87)
SOFT_BG = (240, 253, 244)
RULE = (226, 232, 240)


def _safe(text) -> str:
    """fpdf2 with default fonts (Helvetica) only handles latin-1.

    Strip anything outside that range so a stray em-dash or emoji from
    weather/training-load text doesn't 500 the PDF endpoint.
    """
    if text is None:
        return ''
    s = str(text)
    return s.encode('latin-1', errors='ignore').decode('latin-1')


class _BriefPDF(FPDF):
    def header(self):  # pragma: no cover - layout
        self.set_font('Helvetica', 'B', 9)
        self.set_text_color(*MUTED)
        self.cell(0, 8, 'PaceMind  Race Brief', new_x='LMARGIN', new_y='NEXT', align='L')
        self.set_draw_color(*RULE)
        y = self.get_y()
        self.line(self.l_margin, y, self.w - self.r_margin, y)
        self.ln(4)

    def footer(self):  # pragma: no cover - layout
        self.set_y(-15)
        self.set_font('Helvetica', '', 8)
        self.set_text_color(*MUTED)
        self.cell(
            0, 6,
            'Generated by PaceMind  pacemind.app  Plan, dont predict the future. '
            'Verify nutrition, weather and your body on race day.',
            align='C',
        )


def _kv_row(pdf: FPDF, label: str, value: str, value_bold: bool = False) -> None:
    pdf.set_font('Helvetica', '', 9)
    pdf.set_text_color(*MUTED)
    pdf.cell(45, 6, _safe(label))
    pdf.set_text_color(*INK)
    pdf.set_font('Helvetica', 'B' if value_bold else '', 10)
    pdf.cell(0, 6, _safe(value), new_x='LMARGIN', new_y='NEXT')


def _section_title(pdf: FPDF, title: str) -> None:
    pdf.set_x(pdf.l_margin)
    pdf.ln(2)
    pdf.set_font('Helvetica', 'B', 11)
    pdf.set_text_color(*INK)
    pdf.cell(0, 7, _safe(title.upper()), new_x='LMARGIN', new_y='NEXT')
    pdf.set_draw_color(*RULE)
    y = pdf.get_y()
    pdf.line(pdf.l_margin, y, pdf.w - pdf.r_margin, y)
    pdf.ln(1)


def _format_pct(d: Dict[str, float]) -> str:
    """Turn {'asphalt': 40.0, 'rock': 60.0} into 'asphalt 40% / rock 60%'.

    Values are already percentages: OSMTerrainService.get_terrain_summary
    returns category_breakdown in 0-100.
    """
    if not d:
        return 'unknown'
    parts = sorted(d.items(), key=lambda kv: -kv[1])
    return ' / '.join(f"{k} {round(v)}%" for k, v in parts if v > 0)


def render_race_brief_pdf(brief: Dict, route_name: Optional[str] = None) -> bytes:
    """Render the brief dict into a single-page PDF as raw bytes."""
    pdf = _BriefPDF(format='A4', unit='mm')
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(left=15, top=15, right=15)
    pdf.add_page()

    # ---------- Header / title block ----------
    pdf.set_font('Helvetica', 'B', 22)
    pdf.set_text_color(*INK)
    pdf.cell(
        0, 10, _safe(route_name or f"Race brief #{brief.get('gpx_id')}"),
        new_x='LMARGIN', new_y='NEXT',
    )
    pdf.set_font('Helvetica', '', 10)
    pdf.set_text_color(*MUTED)
    pdf.cell(0, 6, _safe(f"Race date: {brief.get('race_date', '-')}"), new_x='LMARGIN', new_y='NEXT')
    pdf.ln(3)

    # ---------- Prediction box ----------
    prediction = brief.get('prediction') or {}
    ci = prediction.get('confidence_interval') or {}
    pdf.set_fill_color(*SOFT_BG)
    pdf.set_draw_color(*ACCENT)
    box_top = pdf.get_y()
    pdf.rect(pdf.l_margin, box_top, pdf.w - pdf.l_margin - pdf.r_margin, 26, style='DF')

    pdf.set_xy(pdf.l_margin + 4, box_top + 3)
    pdf.set_font('Helvetica', 'B', 9)
    pdf.set_text_color(*MUTED)
    pdf.cell(0, 5, _safe('PREDICTED FINISH'), new_x='LMARGIN', new_y='NEXT')

    pdf.set_x(pdf.l_margin + 4)
    pdf.set_font('Helvetica', 'B', 28)
    pdf.set_text_color(*ACCENT)
    pdf.cell(0, 12, _safe(prediction.get('total_time_formatted') or '--:--:--'),
             new_x='LMARGIN', new_y='NEXT')

    pdf.set_x(pdf.l_margin + 4)
    pdf.set_font('Helvetica', '', 9)
    pdf.set_text_color(*MUTED)
    ci_text = (
        f"Confidence interval: {ci.get('lower_formatted', '?')}  -  {ci.get('upper_formatted', '?')}"
        if ci else 'Confidence interval: unavailable'
    )
    pdf.cell(0, 5, _safe(ci_text), new_x='LMARGIN', new_y='NEXT')
    pdf.set_xy(pdf.l_margin, box_top + 30)

    # ---------- Route ----------
    _section_title(pdf, 'Route')
    route = brief.get('route') or {}
    _kv_row(pdf, 'Distance', f"{route.get('distance_km', 0)} km", value_bold=True)
    _kv_row(pdf, 'Elevation gain', f"{int(route.get('elevation_gain_m', 0))} m", value_bold=True)
    _kv_row(pdf, 'Effort', prediction.get('effort', 'race'))
    _kv_row(pdf, 'Tier used', prediction.get('tier', 'unknown'))

    # ---------- Terrain ----------
    _section_title(pdf, 'Terrain')
    terrain = brief.get('terrain') or {}
    _kv_row(pdf, 'Surface mix', _format_pct(terrain.get('summary')))
    desc = terrain.get('description')
    if desc:
        pdf.set_font('Helvetica', '', 9)
        pdf.set_text_color(*INK)
        pdf.multi_cell(0, 5, _safe(desc))

    # ---------- Weather ----------
    _section_title(pdf, 'Weather')
    weather = brief.get('weather') or {}
    _kv_row(pdf, 'Impact factor', f"x {weather.get('weather_factor', 1.0)}")
    weather_desc = weather.get('description')
    if weather_desc:
        pdf.set_font('Helvetica', '', 9)
        pdf.set_text_color(*INK)
        pdf.multi_cell(0, 5, _safe(weather_desc))

    # ---------- Training status ----------
    _section_title(pdf, 'Your training status')
    training = brief.get('training_status') or {}
    _kv_row(pdf, 'Form', training.get('form', 'unknown'), value_bold=True)
    _kv_row(pdf, 'TSB', f"{training.get('tsb', 0)}")
    interp = training.get('interpretation')
    if interp:
        pdf.set_font('Helvetica', '', 9)
        pdf.set_text_color(*INK)
        pdf.multi_cell(0, 5, _safe(interp))

    # ---------- Key challenges ----------
    challenges = brief.get('key_challenges') or []
    if challenges:
        _section_title(pdf, 'Key challenges')
        pdf.set_font('Helvetica', '', 9)
        pdf.set_text_color(*INK)
        for ch in challenges:
            pdf.set_x(pdf.l_margin)
            pdf.multi_cell(w=pdf.epw, h=5, text=_safe(f"- {ch}"),
                           new_x='LMARGIN', new_y='NEXT')

    return bytes(pdf.output())
